from dataclasses import dataclass
from typing import Protocol


@dataclass
class MoveParams:
    velocity_pct: float
    acceleration_pct: float
    blend_radius_mm: float | None = None


class Robot(Protocol):
    async def run_primitive(self, session_id: str, primitive: str, params: dict) -> None: ...


class RobotControl(Protocol):
    async def upload_program(self, name: str, lua_source: str) -> None: ...
    async def play(self, name: str) -> None: ...
    async def program_state(self) -> str: ...
    async def move_joint(self, joints: list[float], params: MoveParams) -> None: ...
    async def move_linear(self, pose: list[float], params: MoveParams) -> None: ...
    async def move_circular(self, via: list[float], target: list[float], params: MoveParams) -> None: ...
    async def pause(self) -> None: ...
    async def resume(self) -> None: ...
    async def stop(self) -> None: ...


class Camera(Protocol):
    async def start_recording(self) -> None: ...
    async def is_recording(self) -> bool: ...
    async def stop_recording(self) -> None: ...


class Renderer(Protocol):
    async def render(self, session_id: str) -> str: ...
